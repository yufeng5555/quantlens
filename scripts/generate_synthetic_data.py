"""Generate the bundled SYNTHETIC daily OHLCV fixtures for Gate 2.

Deterministic: fixed seeds derived from a constant + symbol name via sha256. Committed
output; re-running reproduces byte-identical CSVs. These series are hand-tuned regime
models keyed to real ETF tickers for UI realism, but they are NOT market data and every
downstream surface labels them SYNTHETIC.

Usage: .venv/bin/python scripts/generate_synthetic_data.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "packages" / "strategy-schema" / "python"))
sys.path.insert(0, str(REPO / "services" / "backtest-worker"))
from quantlens_schema import load_universe  # noqa: E402
from quantlens_worker.snapshot import (  # noqa: E402
    EXPECTED_EXECUTION,
    SNAPSHOT_IDENTITY_VERSION,
    canonical_snapshot_identity,
)

OUT = REPO / "data" / "synthetic"
BASE_SEED = 20260717
START, END = "2004-01-02", "2024-12-31"
GENERATOR_VERSION = "syn-gen-1"

# Per-symbol regime parameters: (bull_drift, bull_vol, bear_drift, bear_vol,
#   p_bull_to_bear, p_bear_to_bull, start_price, mean_reverting)
PARAMS = {
    "SPY": (0.11, 0.13, -0.28, 0.28, 0.004, 0.020, 100.0, False),
    "QQQ": (0.16, 0.18, -0.38, 0.36, 0.004, 0.018, 80.0, False),
    "DIA": (0.09, 0.12, -0.24, 0.26, 0.004, 0.022, 100.0, False),
    "IWM": (0.10, 0.17, -0.30, 0.33, 0.005, 0.018, 60.0, False),
    "EFA": (0.00, 0.15, 0.00, 0.15, 0.010, 0.010, 55.0, True),   # choppy mean-reverter — falsification fodder
    "XLK": (0.14, 0.17, -0.34, 0.34, 0.004, 0.018, 40.0, False),
    "GLD": (0.07, 0.14, -0.10, 0.20, 0.006, 0.015, 45.0, False),
    "TLT": (0.05, 0.12, -0.12, 0.16, 0.006, 0.014, 90.0, False),
}


def symbol_seed(symbol: str) -> int:
    digest = hashlib.sha256(f"{BASE_SEED}:{symbol}".encode()).digest()
    return int.from_bytes(digest[:4], "big")


def make_series(symbol: str, dates: pd.DatetimeIndex) -> pd.DataFrame:
    (bull_mu, bull_sig, bear_mu, bear_sig, p_bb, p_recover, p0, mean_rev) = PARAMS[symbol]
    rng = np.random.default_rng(symbol_seed(symbol))
    n = len(dates)
    dt = 1.0 / 252.0

    if mean_rev:
        # Ornstein-Uhlenbeck around a slowly drifting level: many MA whipsaws, no real trend.
        level = np.log(p0) + np.cumsum(rng.normal(0, 0.0006, n))
        x = np.zeros(n)
        for t in range(1, n):
            x[t] = x[t - 1] - 0.03 * x[t - 1] + rng.normal(0, 0.011)
        log_close = level + x
    else:
        regime_bull = np.ones(n, dtype=bool)
        u = rng.random(n)
        for t in range(1, n):
            if regime_bull[t - 1]:
                regime_bull[t] = u[t] >= p_bb
            else:
                regime_bull[t] = u[t] < p_recover
        mu = np.where(regime_bull, bull_mu, bear_mu)
        sig = np.where(regime_bull, bull_sig, bear_sig)
        shocks = rng.normal(0, 1, n)
        log_ret = (mu - 0.5 * sig**2) * dt + sig * np.sqrt(dt) * shocks
        log_close = np.log(p0) + np.cumsum(log_ret)

    close = np.round(np.exp(log_close), 4)
    gap = rng.normal(0, 0.0018, n)
    open_ = np.round(np.concatenate([[close[0]], close[:-1]]) * (1 + gap), 4)
    hi_pad = np.abs(rng.normal(0, 0.004, n))
    lo_pad = np.abs(rng.normal(0, 0.004, n))
    high = np.round(np.maximum(open_, close) * (1 + hi_pad), 4)
    low = np.round(np.minimum(open_, close) * (1 - lo_pad), 4)
    volume = (rng.integers(2_000, 90_000, n) * 1000).astype(np.int64)

    return pd.DataFrame({
        "date": dates.strftime("%Y-%m-%d"),
        "open": open_, "high": high, "low": low, "close": close, "volume": volume,
    })


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    dates = pd.bdate_range(START, END)
    symbols = [s["symbol"] for s in load_universe()["symbols"]]
    files = {}
    for sym in symbols:
        df = make_series(sym, dates)
        path = OUT / f"{sym}.csv"
        df.to_csv(path, index=False, lineterminator="\n")
        files[f"{sym}.csv"] = hashlib.sha256(path.read_bytes()).hexdigest()
        print(f"wrote {path.name}: {len(df)} rows, close[0]={df['close'].iloc[0]}, close[-1]={df['close'].iloc[-1]}")

    manifest = {
        "identity_version": SNAPSHOT_IDENTITY_VERSION,
        "label": "SYNTHETIC",
        "description": (
            "Bundled synthetic daily OHLCV fixtures for the Gate 2 local prototype. "
            "Generated by a seeded regime model; NOT market data; illustrative only."),
        "generator": {"version": GENERATOR_VERSION, "base_seed": BASE_SEED},
        "calendar": "Business days Mon-Fri, no holiday calendar (synthetic convention).",
        "coverage": {sym: {"start": START, "end": END} for sym in symbols},
        "files": files,
        "splits": {},
        "adjustment_convention": (
            "Prices are fully adjusted at generation; optional splits.csv fixtures are "
            "back-adjusted by the engine (pre-split prices divided by the split ratio)."),
        "execution": dict(EXPECTED_EXECUTION),
    }
    digest, snapshot_id = canonical_snapshot_identity(manifest)
    manifest["sha256"] = digest
    manifest["snapshot_id"] = snapshot_id
    (OUT / "snapshot.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(f"snapshot_id: {manifest['snapshot_id']}")


if __name__ == "__main__":
    main()
